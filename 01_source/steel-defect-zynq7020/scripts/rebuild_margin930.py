"""Source-to-margin930 candidate recipe. Prepared statically; not run in this RC.

Runs Vivado synthesis/implementation, then a fresh-process restored-clock audit.
Does not rebuild HLS, program a board or replace accepted artifacts.
"""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--vivado', type=Path, required=True)
    parser.add_argument('--hls-rtl', type=Path, required=True)
    parser.add_argument('--board-inputs', type=Path, required=True,
                        help='External directory generated by prepare_board_inputs.py')
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    out, rtl, tool = args.out.resolve(), args.hls_rtl.resolve(), args.vivado.resolve()
    board = args.board_inputs.resolve()
    board_lock = json.loads((board/'board_input_lock.json').read_text(encoding='utf-8'))
    for name in ('cnn_system_bd.tcl', 'vendor_ps_parameters.tsv'):
        if sha(board/name) != board_lock['Files'].get(name):
            raise SystemExit('Local board input mismatch: '+name)
    if not tool.is_file() or not (rtl / 'int8_conv3x3.v').is_file():
        raise SystemExit('Missing Vivado executable or generated HLS RTL')
    if 'post_op' not in (rtl / 'int8_conv3x3.v').read_text(encoding='utf-8'):
        raise SystemExit('Generated HLS top lacks the Protocol 2 post_op port')
    if out.is_relative_to(root) or root.is_relative_to(out) or out.is_relative_to(rtl) or rtl.is_relative_to(out):
        raise SystemExit('Source, HLS input and implementation output must be disjoint')
    if out.is_relative_to(board) or board.is_relative_to(out):
        raise SystemExit('Local board inputs and build output must be disjoint')
    if out.exists() and any(out.iterdir()):
        raise SystemExit('Use a new empty output directory')
    out.mkdir(parents=True, exist_ok=True)
    record = {'Status': 'PREPARED_NOT_EXECUTED', 'ToolSHA256': sha(tool),
              'SourceSHA256': {p.relative_to(root).as_posix(): sha(p)
                               for p in (root / 'hardware').rglob('*') if p.is_file()},
              'HLSRTLSHA256': {p.name: sha(p) for p in rtl.glob('*.v')},
              'BoardInputLockSHA256': sha(board/'board_input_lock.json'),
              'Commands': [], 'BoardAccess': False, 'AcceptedResultsReplaced': False}

    def save():
        (out / 'build_record.json').write_text(json.dumps(record, indent=2), encoding='utf-8')

    def run(stage, script, arguments):
        record['Status'] = stage + '_RUNNING'
        save()
        command = [str(tool), '-mode', 'batch', '-notrace', '-source', str(script),
                   '-log', str(out / (stage + '.vivado.log')),
                   '-journal', str(out / (stage + '.vivado.jou')), '-tclargs', *arguments]
        result = subprocess.run(command, cwd=out, capture_output=True, text=True, errors='replace')
        (out / (stage + '.console.log')).write_text(result.stdout + result.stderr, encoding='utf-8')
        record['Commands'].append({'stage': stage, 'command': command, 'exit_code': result.returncode})
        if result.returncode:
            record['Status'] = stage + '_FAILED_STOP'
            save()
            raise SystemExit(result.returncode)

    run('local_ps_normalization', root/'hardware/scripts/normalize_local_ps.tcl',
        [str(board), str(out/'local_ps')])
    record['LocalNormalizedPSSHA256'] = sha(out/'local_ps/vendor_2025_2_effective.tsv')
    save()
    run('source_implementation', root / 'hardware/scripts/build_margin930.tcl',
        ['--hls-rtl', str(rtl), '--board-inputs', str(board),
         '--board-effective', str(out/'local_ps/vendor_2025_2_effective.tsv'),
         '--out', str(out / 'implementation')])
    run('independent_100mhz_audit_export', root / 'hardware/scripts/margin930/audit_restored.tcl',
        ['--dcp', str(out / 'implementation/restored_100mhz.dcp'), '--out', str(out / 'audit_export')])
    artifacts = [out / 'implementation/restored_100mhz.dcp',
                 out / 'audit_export/cnn_system_wrapper.bit',
                 out / 'audit_export/margin930_rebuilt_100mhz.xsa']
    if not all(p.is_file() for p in artifacts):
        record['Status'] = 'MISSING_ARTIFACT_STOP'
        save()
        raise SystemExit('Vivado exited without all expected artifacts')
    record.update(Status='REBUILT_AUDITED_CANDIDATE_NOT_BOARD_MEASURED',
                  ArtifactSHA256={p.relative_to(out).as_posix(): sha(p) for p in artifacts})
    save()


if __name__ == '__main__':
    main()
